"""Regenerate docs/DATASETS.md — the map of what training data exists and how to grow it.

Counts are read from the data, never hand-maintained, so the doc cannot drift from reality. Re-run after any generation
run or SFT rebuild:

  python scripts/dataset_index.py
"""
from __future__ import annotations

import json
import re
import sys
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
PHASE1 = REPO / "phase1"
SEGMENTS = ["sky", "ground", "camera", "vegetation", "fauna", "effects"]

# What each run-tag family means. Tags are <segment>_<tag>; the tag says how the layers in it were produced.
TAG_KINDS = [
    (r"^train\d*$|^baseline_train$", "teacher", "Fable wrote these from sampled briefs — the base training data"),
    (r"^car\d*$|^baseline_car$", "critique-and-revise", "the specialist's own failures, repaired by Fable"),
    (r"^salvage$", "salvage", "mechanically repaired teacher layers (sky: gl_FragColor added)"),
    (r"^golden$|_golden$", "golden", "hand-written reference layers"),
    (r"fable", "ceiling", "Fable scored on the held-out eval briefs — the target to beat"),
    (r"spec|sft|rl|vis|27b", "eval", "a specialist scored on the held-out eval briefs"),
    (r"^smoke", "smoke", "2-brief plumbing checks"),
    (r"^r4$|r4-", "baseline", "the untrained generalist — the floor"),
]


def kind_of(tag: str) -> tuple[str, str]:
    for pat, kind, desc in TAG_KINDS:
        if re.search(pat, tag):
            return kind, desc
    return "other", ""


def run_stats(d: Path) -> tuple[int, int]:
    rows = {}
    for line in (d / "log.jsonl").read_text().splitlines():
        try:
            r = json.loads(line)
        except Exception:  # noqa: BLE001
            continue
        rows[r.get("id")] = r
    return len(rows), sum(1 for r in rows.values() if r.get("pass"))


def main() -> None:
    runs = []
    for d in sorted(PHASE1.glob("*_*")):
        if not (d / "log.jsonl").exists():
            continue
        seg, _, tag = d.name.partition("_")
        if seg not in SEGMENTS:
            continue
        kind, _desc = kind_of(tag)
        n, p = run_stats(d)
        runs.append({"segment": seg, "tag": tag, "kind": kind, "briefs": n, "passing": p, "dir": d.name})

    usable = Counter()
    for r in runs:
        if r["kind"] in ("teacher", "critique-and-revise", "salvage", "golden"):
            usable[r["segment"]] += r["passing"]

    out = ["# Training datasets",
           "",
           f"_Generated by `scripts/dataset_index.py` on {time.strftime('%Y-%m-%d', time.gmtime())}. Do not hand-edit._",
           "",
           "## How the data is organised",
           "",
           "Three layers, in dependency order:",
           "",
           "1. **Raw runs** — `data/<segment>_<tag>/`. One directory per generation run: every candidate layer (`cand-*.js`),",
           "   its assembled page (`build-*.cdn.html`) and `log.jsonl` with the gate + check results per brief. These are the",
           "   base datasets. They are **append-only**: nothing rewrites them, and each is mirrored to",
           "   `s3://<your-bucket>/<prefix>/gen/<segment>_<tag>/` as the job runs.",
           "2. **Built SFT sets** — `data/<segment>_sft_{train,val}.jsonl`, produced by `build_segment_sft.py` from one or more",
           "   raw runs. These are **derived and overwritten** on every build; the sidecar `<segment>_sft.meta.json` records the",
           "   exact sources, filters and row counts, and carries the command that rebuilds that set.",
           "3. **Adapters** — `adapters/adapter-<segment>-<size>-<tag>/`, backed up to `…/threejs-specialist/adapters/` with",
           "   `ADAPTERS.json` naming the best adapter per segment and its held-out score.",
           "",
           "## Run kinds",
           "",
           "| tag pattern | kind | what it is |",
           "| --- | --- | --- |"]
    for pat, kind, desc in TAG_KINDS:
        out.append(f"| `{pat}` | {kind} | {desc} |")

    out += ["", "## Raw runs on disk", "",
            "Only **teacher**, **critique-and-revise**, **salvage** and **golden** runs feed training; ceiling and eval runs are",
            "measurements. `passing` is what a rebuild would draw from (minus any brief that collides with the held-out eval set).",
            "", "| segment | tag | kind | briefs | passing |", "| --- | --- | --- | ---: | ---: |"]
    for r in runs:
        out.append(f"| {r['segment']} | `{r['tag']}` | {r['kind']} | {r['briefs']} | {r['passing']} |")

    out += ["", "## Built sets in use", "", "| segment | train | val | sources | filter | usable rows available |",
            "| --- | ---: | ---: | --- | --- | ---: |"]
    for seg in SEGMENTS:
        meta_p = PHASE1 / f"{seg}_sft.meta.json"
        if not meta_p.exists():
            out.append(f"| {seg} | — | — | _no meta yet_ | | {usable[seg]} |")
            continue
        m = json.loads(meta_p.read_text())
        filt = f"min-herd-p98 {m['min_herd_p98']}" if m.get("min_herd_p98") else "—"
        out.append(f"| {seg} | {m['train_rows']} | {m['val_rows']} | `{m['sources']}` | {filt} | {usable[seg]} |")

    planner_meta = PHASE1 / "planner_sft.meta.json"
    if planner_meta.exists():
        m = json.loads(planner_meta.read_text())
        out += ["", "## Planner", "",
                f"- built sets: `phase1/planner_sft_{{train,val}}.jsonl` ({m['train_rows']} / {m['val_rows']} rows)",
                f"- source plans: {', '.join('`' + s + '`' for s in m['sources'])}",
                f"- dropped for breaking the output contract: {m['dropped_contract_breaking']}",
                "- themes come from `scenes/phase1/theme_briefs.py` (seed 2 trains, seed 1 is held out)"]

    out += ["", "## Scaling the data", "",
            "**More of the same segment** — run the teacher on fresh briefs, then add the new tag to the sources:",
            "",
            "```",
            "python pipeline/sagemaker/launch_job.py gen --segment fauna --tag train4 --seed 8 --n 96 --wait --download",
            "python pipeline/build_sft.py --segment fauna --sources train,car,train2,train3,train4",
            "```",
            "",
            "Use a new `--seed` per run: seeds 1 (eval) and 2 are taken, and two runs with the same seed produce the same briefs.",
            "Re-running an existing tag **resumes** it (rows are keyed by brief id) rather than adding new briefs.",
            "",
            "**A harder segment** — generate the specialist's failures and let the teacher repair them:",
            "",
            "```",
            "python pipeline/sagemaker/launch_job.py serve --segment fauna --adapter adapters/adapter-rl/<adapter> \\",
            "    --tag car2 --seed 5 --n 96 --reviser fable --wait --download",
            "```",
            "",
            "**A new scene** — everything above is `highpark`-only: `groundH`, the meadow at (12, -46) and the calibrated checks",
            "all assume that host. A second host (`scenes/seastate`, `scenes/cenote`) needs its own reference renders and check",
            "thresholds in `pipeline/harness/layer_harness.py` before its data means anything.",
            "",
            "**Rule of thumb from what we have:** a segment needs roughly 150+ passing rows to train well; camera reached 92% on 76,",
            "vegetation needed two critique-and-revise rounds to reach 176, and fauna did not clear ~21% on 176 at 8B — its ceiling",
            "was model size, not data volume.",
            ""]

    doc = REPO / "docs" / "DATASETS.md"
    doc.write_text("\n".join(out))
    print(f"wrote {doc} | {len(runs)} raw runs | usable rows per segment: {dict(usable)}")


if __name__ == "__main__":
    main()
